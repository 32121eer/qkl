#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { performance } = require('node:perf_hooks');
const {
    buildCases, parseVerdict, pearson, summarizeSamples, writeDataset
} = require('./extended_model_benchmark');

const endpoint = process.env.OLLAMA || 'http://127.0.0.1:11434';
const models = (process.env.MODELS || 'llama3.2:1b,qwen2.5:1.5b').split(',').filter(Boolean);
const repeats = Number(process.env.REPEATS || 1);
const outputDirectory = path.resolve(process.env.OUTPUT_DIR || path.join(__dirname, 'results'));

function prompt(item) {
    return 'You are a cross-chain evidence verifier. Apply only the stated rule. ' +
        'Return JSON only: {"judgment":"ACCEPT"|"REJECT","confidence":0..1}. ' +
        'ACCEPT means the evidence satisfies the rule.\n\n' + item.text;
}

async function infer(model, item) {
    const started = performance.now();
    const response = await fetch(`${endpoint}/api/generate`, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
            model,
            prompt: prompt(item),
            stream: false,
            format: 'json',
            options: { temperature: 0.3, num_predict: 100 }
        }),
        signal: AbortSignal.timeout(Number(process.env.MODEL_TIMEOUT_MS || 120000))
    });
    if (!response.ok) throw new Error(`Ollama ${model}: HTTP ${response.status}`);
    const body = await response.json();
    const verdict = parseVerdict(body.response);
    if (!verdict) throw new Error(`Ollama ${model}: invalid structured response`);
    return {
        ...verdict,
        latencyMs: Number((performance.now() - started).toFixed(3)),
        evalCount: body.eval_count ?? null
    };
}

async function main() {
    if (models.length < 2) throw new Error('At least two models are required for cross-model error correlation');
    if (!Number.isInteger(repeats) || repeats < 1) throw new Error('REPEATS must be a positive integer');
    const cases = buildCases();
    writeDataset(outputDirectory);
    const samples = Object.fromEntries(models.map((model) => [model, []]));
    for (const item of cases) {
        for (let repeat = 0; repeat < repeats; repeat += 1) {
            for (const model of models) {
                try {
                    const value = await infer(model, item);
                    samples[model].push({
                        caseId: item.id, family: item.family, truth: item.truth, repeat,
                        ...value, correct: value.judgment === item.truth, error: null
                    });
                } catch (error) {
                    samples[model].push({
                        caseId: item.id, family: item.family, truth: item.truth, repeat,
                        judgment: null, confidence: null, latencyMs: null, evalCount: null,
                        correct: false, error: error.message
                    });
                }
                const latest = samples[model][samples[model].length - 1];
                process.stdout.write(`${item.id} r${repeat} ${model}: ${latest.judgment || 'ERROR'}\n`);
            }
        }
    }
    const byModel = Object.fromEntries(models.map((model) => [model, summarizeSamples(samples[model])]));
    const completedByKey = (model) => new Map(samples[model]
        .filter((sample) => !sample.error)
        .map((sample) => [`${sample.caseId}:${sample.repeat}`, sample.correct ? 0 : 1]));
    const left = completedByKey(models[0]);
    const right = completedByKey(models[1]);
    const common = [...left.keys()].filter((key) => right.has(key));
    const report = {
        schemaVersion: 'semantic-model-benchmark-results-v1',
        generatedAt: new Date().toISOString(),
        backend: 'ollama', endpoint, models, repeats,
        caseCount: cases.length,
        inferenceCount: cases.length * repeats * models.length,
        environment: {
            platform: `${os.platform()} ${os.release()} ${os.arch()}`,
            cpu: os.cpus()[0]?.model || null,
            logicalCpus: os.cpus().length,
            memoryGiB: Number((os.totalmem() / (1024 ** 3)).toFixed(2))
        },
        labelSource: 'deterministic rule oracle independent of evaluated models',
        byModel,
        crossModelErrorCorrelation: pearson(common.map((key) => left.get(key)), common.map((key) => right.get(key))),
        commonCompletedSamples: common.length,
        evidenceBoundary: [
            'Labels are generated by explicit date, amount, tolerance, range and FX rules; they are independent of model outputs',
            'The benchmark measures two local model artifacts and does not estimate all commercial or open models',
            'Human double-annotation columns are supplied separately but are not claimed unless completed'
        ]
    };
    fs.writeFileSync(path.join(outputDirectory, 'raw_samples.json'), `${JSON.stringify({ models, cases, samples }, null, 2)}\n`);
    fs.writeFileSync(path.join(outputDirectory, 'summary.json'), `${JSON.stringify(report, null, 2)}\n`);
    if (Object.values(byModel).some((summary) => summary.completed !== summary.requested)) {
        throw new Error(`Incomplete real-model run; inspect ${path.join(outputDirectory, 'summary.json')}`);
    }
    process.stdout.write(`${path.join(outputDirectory, 'summary.json')}\n`);
}

if (require.main === module) main().catch((error) => {
    process.stderr.write(`${error.stack || error}\n`);
    process.exitCode = 1;
});

module.exports = { infer, main, prompt };
